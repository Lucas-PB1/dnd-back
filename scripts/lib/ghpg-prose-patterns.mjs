export function applyGhpgProsePatterns(text) {
  if (!text) return text;
  let out = text;
  for (let pass = 0; pass < 3; pass += 1) {
    let next = out;
    for (const [pattern, replacement] of GHPG_PROSE_PATTERNS) {
      next = next.replace(pattern, replacement);
    }
    if (next === out) break;
    out = next;
  }
  return out;
}
